test('v1.0.0 cert: all version surfaces agree', () => {
  const ri = readJson('config/release-identity.json');
  const pkg = readJson('package.json');
  const versionJs = readText('apps/lab-web/src/version.js');
  const versionMjs = readText('packages/shared/src/version.mjs');
  const v1 = ri.version;
  const v2 = pkg.version;
  const v3 = versionJs.match(/LAB_VERSION\s*=\s*['"]([^'"]+)['"]/)?.[1];
  const v4 = versionMjs.match(/LAB_VERSION\s*=\s*['"]([^'"]+)['"]/)?.[1];
  assert.equal(v2, v1, `package.json ${v2} != release-identity ${v1}`);
  assert.equal(v3, v1, `version.js ${v3} != release-identity ${v1}`);
  assert.equal(v4, v1, `version.mjs ${v4} != release-identity ${v1}`);
});

