// ── Certification gate framework ────────────────────────────────

test('v1.0.0 cert: certification gate framework has 6 gates', async () => {
  const { CERTIFICATION_GATES } = await import('../scripts/certification-gates.mjs');
  assert.equal(Object.keys(CERTIFICATION_GATES).length, 6, 'Must have exactly 6 certification gates');
  const expectedKeys = ['rules-engine', 'local-experience', 'online-experience', 'laboratory', 'release-engineering', 'human-validation'];
  for (const key of expectedKeys) {
    assert.ok(CERTIFICATION_GATES[key], `Gate ${key} must exist`);
    assert.ok(typeof CERTIFICATION_GATES[key].fn === 'function', `Gate ${key} must have a function`);
    assert.ok(CERTIFICATION_GATES[key].name, `Gate ${key} must have a name`);
  }
});

test('v1.0.0 cert: each gate returns structured result with evidence', async () => {
  const { CERTIFICATION_GATES } = await import('../scripts/certification-gates.mjs');
  for (const [key, gate] of Object.entries(CERTIFICATION_GATES)) {
    const result = gate.fn();
    assert.ok(typeof result.passed === 'boolean', `Gate ${key} must return boolean passed`);
    assert.ok(Array.isArray(result.evidence), `Gate ${key} must return evidence array`);
    assert.ok(Array.isArray(result.gaps), `Gate ${key} must return gaps array`);
    assert.ok(result.evidence.length > 0, `Gate ${key} must have at least one evidence item`);
  }
});
