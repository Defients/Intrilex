test('self-audit: synthetic accounting mismatch cannot produce PASS (v0.24.2 regression)', () => {
  // Prove the generator's status logic rejects non-zero unaccounted.
  // Simulate the exact arithmetic the generator uses.
  const totalTests = 100;
  const totalPass = 99;
  const totalFail = 0;
  const totalSkip = 0;
  const totalCancelled = 0;
  const totalTodo = 0;
  const accounted = totalPass + totalFail + totalSkip + totalCancelled + totalTodo;
  const unaccounted = totalTests - accounted; // = 1

  // The generator's status condition (v0.24.2):
  const score = 97;
  const threshold = 92;
  const criticalGates = {
    canonDefect: totalFail === 0,
    testAccountingReconciled: unaccounted === 0,
  };
  const status = (totalFail === 0 && score >= threshold && unaccounted === 0 &&
    Object.values(criticalGates).every(v => v === true)) ? 'PASS' : 'FAIL';

  assert.equal(unaccounted, 1, 'synthetic mismatch should produce unaccounted=1');
  assert.equal(criticalGates.testAccountingReconciled, false,
    'testAccountingReconciled gate must be false when unaccounted=1');
  assert.equal(status, 'FAIL',
    'status must be FAIL when unaccounted !== 0, even if all other gates pass');
});
