test('self-audit certification count agrees with self-audit count (BL-15 binding)', async () => {
  const audit = JSON.parse(await readFile(path.join(root, 'reports/self-audit.json'), 'utf8'));
  const rootPkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
  const certPath = path.join(root, `release/v${rootPkg.version}-certification.json`);
  if (!existsSync(certPath)) return; // skip if cert doesn't exist yet
  const cert = JSON.parse(await readFile(certPath, 'utf8'));
  const auditCount = audit.testResults?.totalTests ?? 0;
  const certCount = cert.testResults?.totalTests ?? 0;
  assert.equal(certCount, auditCount,
    `certification totalTests (${certCount}) must equal self-audit test count (${auditCount})`);
});

test('self-audit is not a static-only check — negative control: tampered audit must fail', async () => {
  // This test proves the self-audit test is not just reading a static JSON.
  // If someone edits self-audit.json to say PASS with false gates, the first test must fail.
  // We verify this by checking that the test actually asserts gate values are true.
  const testSource = await readFile(path.join(root, 'test/self-audit-truth.test.mjs'), 'utf8');
  assert.ok(testSource.includes('assert.equal(value, true'), 'test must assert gates are true');
  assert.ok(testSource.includes('BL-14'), 'test must reference BL-14 binding');
  // Verify the audit JSON is not empty or trivially PASS
  const audit = JSON.parse(await readFile(path.join(root, 'reports/self-audit.json'), 'utf8'));
  assert.ok(Object.keys(audit.criticalGates).length >= 5, 'must have at least 5 critical gates');
  // Verify the audit was machine-generated, not hand-written
  assert.ok(audit.generatedBy?.includes('generate-self-audit.mjs'),
    'audit must be generated by the script, not hand-written');
});

