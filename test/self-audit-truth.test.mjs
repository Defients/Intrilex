test('self-audit test count matches actual executed test count (BL-14 binding)', async () => {
  // Read the self-audit JSON
  const audit = JSON.parse(await readFile(path.join(root, 'reports/self-audit.json'), 'utf8'));
  const claimed = audit.testResults?.defaultTestSuite ?? '';
  const claimedMatch = claimed.match(/(\d+)\s+tests,\s+(\d+)\s+pass,\s+(\d+)\s+fail/);
  assert.ok(claimedMatch, `defaultTestSuite must be in format 'N tests, N pass, N fail', got: ${claimed}`);
  const claimedTests = parseInt(claimedMatch[1]);
  const claimedPass = parseInt(claimedMatch[2]);
  const claimedFail = parseInt(claimedMatch[3]);

  assert.ok(claimedTests > 0, 'claimed test count must be > 0');
  assert.equal(claimedFail, 0, 'claimed fail count must be 0 for PASS status');

  // Verify the test files exist on disk
  const testDir = path.join(root, 'test');
  const testFiles = (await readdir(testDir)).filter(f => f.endsWith('.test.mjs'));
  assert.ok(testFiles.length >= 20, `Must have at least 20 test files, got ${testFiles.length}`);

  // BL-14 REAL BINDING: Statically count test() and it() calls across all test files.
  // This is a conservative lower bound — if the claimed count is less than the
  // static count, the audit is fabricated. If someone hardcodes a number,
  // this catches it because the static count reflects the actual code.
  let staticTestCount = 0;
  for (const file of testFiles) {
    const source = await readFile(path.join(testDir, file), 'utf8');
    // Count test(...) and it(...) calls — match word boundary to avoid false positives
    // Matches: test('...', ...), test("...", ...), it('...', ...), it("...", ...)
    const testMatches = source.match(/\btest\s*\(/g);
    const itMatches = source.match(/\bit\s*\(/g);
    staticTestCount += (testMatches?.length ?? 0) + (itMatches?.length ?? 0);
  }

  // The claimed total must be >= the static count minus a tolerance for
  // test() calls that are in describe blocks but counted differently by the runner.
  // The static count includes describe() wrappers which are counted as suites,
  // not tests, so we need to subtract describe() calls.
  let describeCount = 0;
  for (const file of testFiles) {
    const source = await readFile(path.join(testDir, file), 'utf8');
    const describeMatches = source.match(/\bdescribe\s*\(/g);
    describeCount += describeMatches?.length ?? 0;
  }
  const expectedTestCount = staticTestCount - describeCount;

  // The claimed count must be close to the static count (within 15% to account
  // for conditional skips, dynamic tests, and counting differences)
  assert.ok(claimedTests >= Math.floor(expectedTestCount * 0.85),
    `claimed test count (${claimedTests}) must be >= 85% of static test count (${expectedTestCount}) — if claimed is far below static, the count is fabricated`);

  // The claimed count must not be the v1.0.0 hardcoded value
  assert.ok(claimedTests !== 395,
    `claimed test count must not be the v1.0.0 hardcoded value 395, got ${claimedTests}`);

  // The claimed count must be plausible: at least as many as testFiles * 2
  assert.ok(claimedTests >= testFiles.length * 2,
    `claimed test count (${claimedTests}) must be plausible for ${testFiles.length} test files`);

  // The audit must report the actual number of test files executed
  assert.ok(audit.testResults?.filesExecuted > 0,
    'audit must report filesExecuted > 0');
  assert.ok(audit.testResults?.testFileCount >= testFiles.length,
    `audit testFileCount (${audit.testResults?.testFileCount}) must be >= actual test files (${testFiles.length})`);
});

